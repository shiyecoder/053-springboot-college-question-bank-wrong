  UNIQUE KEY `uk_subject_no` (`subject_no`),
  UNIQUE KEY `uk_subject_name` (`subject_name`),
  KEY `idx_status_sort` (`status`, `sort_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='学科';

