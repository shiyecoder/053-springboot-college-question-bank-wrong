-- 3. question 题目
CREATE TABLE `question` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `question_no` varchar(32) NOT NULL COMMENT '规则 TM+学科码+6位序号，全局唯一',
  `subject_id` bigint NOT NULL COMMENT '关联 subject.id',
